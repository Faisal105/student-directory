CREATE TABLE dbo.Students (
 StudentId INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Students PRIMARY KEY,
 Name NVARCHAR(100) NOT NULL,
 Email NVARCHAR(100) NOT NULL CONSTRAINT UQ_Students_Email UNIQUE,
 Phone NVARCHAR(20) NOT NULL,
 Department NVARCHAR(50) NOT NULL,
 CreatedDate DATETIME NOT NULL CONSTRAINT DF_Students_CreatedDate DEFAULT GETUTCDATE()
);
CREATE TABLE dbo.Users (
 UserId INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Users PRIMARY KEY,
 Email NVARCHAR(100) NOT NULL CONSTRAINT UQ_Users_Email UNIQUE,
 PasswordHash NVARCHAR(255) NOT NULL,
 IsActive BIT NOT NULL DEFAULT 1,
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
CREATE TABLE dbo.Sessions (
 TokenHash CHAR(64) NOT NULL CONSTRAINT PK_Sessions PRIMARY KEY,
 UserId INT NOT NULL REFERENCES dbo.Users(UserId) ON DELETE CASCADE,
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
 ExpiresAt DATETIME2 NOT NULL
);
CREATE INDEX IX_Sessions_ExpiresAt ON dbo.Sessions(ExpiresAt);
CREATE ROLE student_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON dbo.Students TO student_app;
GRANT SELECT, INSERT, DELETE ON dbo.Sessions TO student_app;
GRANT SELECT ON dbo.Users TO student_app;
